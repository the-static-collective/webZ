const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const html = fs.readFileSync(path.join(__dirname,'Human_Entry_001_Offline.html'),'utf8');
const js = html.match(/<script>([\s\S]*?)<\/script>/)[1];
const core = js.slice(js.indexOf("var SCHEMA="), js.indexOf('window.HumanEntry001='));
const context = {Date,Math,Error};
vm.createContext(context);
vm.runInContext(core + '\nthis.api={newBoard,advance,refuse,canAdvance,validShape,packet};',context);
const api=context.api;
const b=api.newBoard();
assert.match(api.canAdvance(b),/title/);
b.title='Fictional welcome table';b.description='No venue authorization; practice only.';
assert.match(api.canAdvance(b),/Chair empty: host/);
b.roles={host:'Harbor',steward:'Moss',participant:'River',witness:'River',reviewer:'Lantern'};
for(let i=0;i<4;i++)api.advance(b);
assert.equal(b.stage,'WORK_REPORTED');
assert.match(api.canAdvance(b),/conflict/);
b.roles.witness='Juniper';b.roles.reviewer='River';
api.advance(b);
assert.match(api.canAdvance(b),/conflict/);
b.roles.reviewer='Lantern';api.advance(b);
assert.equal(b.stage,'REVIEW_CONFIRMED');
assert.equal(b.events.length,6);
assert.throws(()=>api.advance(b),/finished/);
const p=api.packet(b);
assert.equal(p.signature,'NONE');
assert.equal(p.status,'UNSIGNED_NOTE_NOT_FIELD_PROOF');
assert.equal(api.validShape(p.board),true);
const c=api.newBoard();c.roles.host='Harbor';api.refuse(c,'host','not now');
assert.equal(c.stage,'REFUSED');assert.throws(()=>api.advance(c),/finished/);
assert.equal(c.events[0].kind,'REFUSE');
console.log('PASS Human Entry 001: empty chair, ordered stages, independence guard, terminal refusal, unsigned portable note');
