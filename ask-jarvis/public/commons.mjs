// Fixed stopwords keep the match trace readable and stable. No embeddings,
// model calls, network requests, accounts or visitor behavior logs.
const STOP=new Set(['the','and','or','with','for','from','into','about','that','this','what','which',
  'could','would','should','when','where','there','have','has','been','make','using','people','we',
  'can','our','your','one','some','how','does','next','any','thing','who','are','its','they']);
const terms=s=>[...new Set((String(s).toLowerCase().match(/[a-z0-9]+/g)||[])
  .filter(t=>t.length>=3&&!STOP.has(t)))];
const norm=term=>term.endsWith('ies')?term.slice(0,-3)+'y'
  :term.endsWith('s')&&term.length>4?term.slice(0,-1):term;
const score=(entry,wanted)=>{
  const labels=new Set(terms(entry.lane.replace(/_/g,' ')+' '+entry.tags.join(' ')).map(norm));
  const observed=new Set(terms(entry.observation+' '+entry.firstCheck).map(norm));
  let total=0;
  for(const word of wanted) {
    if(labels.has(word))total+=6;
    if(observed.has(word))total+=1;
  }
  return total;
};
/** Return a bounded snapshot of the most relevant *curated* summaries.
 * This is relevance selection, NOT proof of evidence, human consent or truth.
 */
export function selectCommons(question,{limit=6}={}) {
  if(typeof question!=='string'||question.length>360)throw Error('COMMONS_QUESTION_INVALID');
  const wanted=[...new Set(terms(question).map(norm))];
  const ranked=COMMONS_ENTRIES.map((entry,index)=>({entry,index,score:score(entry,wanted)}))
    .sort((a,b)=>b.score-a.score||a.index-b.index);
  const selected=[];const lanes=new Set();
  const positive=ranked.filter(x=>x.score>0);
  for(const item of positive){if(!lanes.has(item.entry.lane)&&selected.length<limit){
    selected.push(item);lanes.add(item.entry.lane);}}
  for(const item of positive){if(selected.length>=limit)break;if(!selected.includes(item))selected.push(item);}
  if(!selected.length)selected.push(...ranked.slice(0,Math.min(3,limit)));
  return selected.slice(0,limit).map(({entry,score})=>({
    id:entry.id,lane:entry.lane,status:entry.status,sourceId:entry.sourceId,
    observation:entry.observation,firstCheck:entry.firstCheck,
    relevance:score>0?'KEYWORD_MATCH':'STARTER_CONTEXT'
  }));
}
export function publicCommonsFor(question) {
  return {schema:'jarvis/public-commons-v1',release:COMMONS_RELEASE,
    trust:'SITE_CURATED_EDITORIAL_SNAPSHOT_NOT_VERIFIED_REAL_WORLD',
    disclosure:COMMONS_DISCLOSURE,selected:selectCommons(question)};
}
